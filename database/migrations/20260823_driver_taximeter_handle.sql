create or replace function public.taximeter_distance_m(p_lat1 double precision,p_lng1 double precision,p_lat2 double precision,p_lng2 double precision)
returns numeric language sql immutable set search_path to 'pg_catalog','public' as $$
  select 6371000 * 2 * asin(sqrt(power(sin(radians(p_lat2-p_lat1)/2),2) + cos(radians(p_lat1))*cos(radians(p_lat2))*power(sin(radians(p_lng2-p_lng1)/2),2)));
$$;
revoke all on function public.taximeter_distance_m(double precision,double precision,double precision,double precision) from public,anon,authenticated;

create or replace function public.get_my_taximeter_categories()
returns table(category_id uuid,category_name text,base_fare numeric,price_per_km numeric,price_per_minute numeric,minimum_fare numeric,multiplier numeric)
language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare v_uid uuid:=auth.uid(); v_driver public.drivers%rowtype;
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  select * into v_driver from public.drivers where id=v_uid;
  if not found or v_driver.status::text<>'approved' then raise exception 'Motorista ainda não está aprovado'; end if;
  return query
  select c.id,c.name,c.base_fare,c.price_per_km,c.price_per_minute,c.minimum_fare,greatest(coalesce(c.dynamic_multiplier,1),1)
  from public.ride_categories c
  where c.active=true and c.city_id is not distinct from v_driver.city_id and c.franchise_id is not distinct from v_driver.franchise_id
    and (not exists(select 1 from public.driver_category_eligibility e0 where e0.driver_id=v_uid) or exists(select 1 from public.driver_category_eligibility e where e.driver_id=v_uid and e.category_id=c.id and e.active=true))
  order by c.name;
end;
$$;
revoke all on function public.get_my_taximeter_categories() from public,anon;
grant execute on function public.get_my_taximeter_categories() to authenticated;

create or replace function public.start_driver_taximeter(p_category_id uuid,p_lat double precision,p_lng double precision)
returns jsonb language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare v_uid uuid:=auth.uid(); v_driver public.drivers%rowtype; v_cat public.ride_categories%rowtype; v_id uuid; v_amount numeric;
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  if p_lat not between -90 and 90 or p_lng not between -180 and 180 then raise exception 'Localização inválida'; end if;
  select * into v_driver from public.drivers where id=v_uid for update;
  if not found or v_driver.status::text<>'approved' then raise exception 'Motorista não aprovado'; end if;
  if exists(select 1 from public.rides r where r.driver_id=v_uid and r.status::text in ('accepted','driver_arriving','in_progress')) then raise exception 'Finalize a corrida CLICK-GO ativa antes de usar o taxímetro livre'; end if;
  if exists(select 1 from public.driver_taximeter_sessions s where s.driver_id=v_uid and s.status='running') then raise exception 'Já existe um taxímetro em andamento'; end if;
  select * into v_cat from public.ride_categories c where c.id=p_category_id and c.active=true and c.city_id is not distinct from v_driver.city_id and c.franchise_id is not distinct from v_driver.franchise_id;
  if not found then raise exception 'Categoria indisponível para este motorista'; end if;
  if exists(select 1 from public.driver_category_eligibility e0 where e0.driver_id=v_uid) and not exists(select 1 from public.driver_category_eligibility e where e.driver_id=v_uid and e.category_id=p_category_id and e.active=true) then raise exception 'Categoria não autorizada para este motorista'; end if;
  v_amount:=round(greatest(coalesce(v_cat.minimum_fare,0),coalesce(v_cat.base_fare,0))*greatest(coalesce(v_cat.dynamic_multiplier,1),1),2);
  insert into public.driver_taximeter_sessions(driver_id,franchise_id,city_id,category_id,base_fare,price_per_km,price_per_minute,minimum_fare,multiplier,start_lat,start_lng,last_lat,last_lng,current_amount)
  values(v_uid,v_driver.franchise_id,v_driver.city_id,v_cat.id,coalesce(v_cat.base_fare,0),coalesce(v_cat.price_per_km,0),coalesce(v_cat.price_per_minute,0),coalesce(v_cat.minimum_fare,0),greatest(coalesce(v_cat.dynamic_multiplier,1),1),p_lat,p_lng,p_lat,p_lng,v_amount) returning id into v_id;
  insert into public.driver_taximeter_points(session_id,driver_id,lat,lng,distance_from_prev_m,accepted) values(v_id,v_uid,p_lat,p_lng,0,true);
  return jsonb_build_object('ok',true,'session_id',v_id,'status','running','amount',v_amount,'started_at',now());
end;
$$;
revoke all on function public.start_driver_taximeter(uuid,double precision,double precision) from public,anon;
grant execute on function public.start_driver_taximeter(uuid,double precision,double precision) to authenticated;

create or replace function public.tick_driver_taximeter(p_session_id uuid,p_lat double precision,p_lng double precision)
returns jsonb language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare v_uid uuid:=auth.uid(); v_s public.driver_taximeter_sessions%rowtype; v_step numeric:=0; v_delta_s integer:=0; v_total_s integer:=0; v_max_step numeric:=0; v_accept boolean:=true; v_distance numeric:=0; v_amount numeric:=0;
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  if p_lat not between -90 and 90 or p_lng not between -180 and 180 then raise exception 'Localização inválida'; end if;
  select * into v_s from public.driver_taximeter_sessions where id=p_session_id and driver_id=v_uid for update;
  if not found or v_s.status<>'running' then raise exception 'Taxímetro não está em andamento'; end if;
  v_delta_s:=greatest(1,floor(extract(epoch from (now()-v_s.last_tick_at)))::integer);
  v_total_s:=greatest(0,floor(extract(epoch from (now()-v_s.started_at)))::integer);
  if v_s.last_lat is not null and v_s.last_lng is not null then v_step:=public.taximeter_distance_m(v_s.last_lat,v_s.last_lng,p_lat,p_lng); end if;
  v_max_step:=greatest(120::numeric,v_delta_s*70::numeric);
  if v_step>v_max_step then v_accept:=false; end if;
  v_distance:=v_s.distance_m + case when v_accept then coalesce(v_step,0) else 0 end;
  v_amount:=round(greatest(v_s.minimum_fare,(v_s.base_fare + (v_distance/1000.0)*v_s.price_per_km + (v_total_s/60.0)*v_s.price_per_minute)*v_s.multiplier),2);
  update public.driver_taximeter_sessions set last_tick_at=now(),last_lat=p_lat,last_lng=p_lng,distance_m=v_distance,elapsed_seconds=v_total_s,current_amount=v_amount,updated_at=now() where id=v_s.id;
  insert into public.driver_taximeter_points(session_id,driver_id,lat,lng,distance_from_prev_m,accepted) values(v_s.id,v_uid,p_lat,p_lng,v_step,v_accept);
  return jsonb_build_object('ok',true,'session_id',v_s.id,'status','running','amount',v_amount,'distance_m',v_distance,'elapsed_seconds',v_total_s,'point_accepted',v_accept);
end;
$$;
revoke all on function public.tick_driver_taximeter(uuid,double precision,double precision) from public,anon;
grant execute on function public.tick_driver_taximeter(uuid,double precision,double precision) to authenticated;

create or replace function public.finish_driver_taximeter(p_session_id uuid,p_lat double precision,p_lng double precision,p_payment_method text default null)
returns jsonb language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare v_uid uuid:=auth.uid(); v_tick jsonb; v_amount numeric; v_distance numeric; v_elapsed integer;
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  perform 1 from public.driver_taximeter_sessions where id=p_session_id and driver_id=v_uid and status='running';
  if not found then raise exception 'Taxímetro não está em andamento'; end if;
  v_tick:=public.tick_driver_taximeter(p_session_id,p_lat,p_lng);
  select current_amount,distance_m,elapsed_seconds into v_amount,v_distance,v_elapsed from public.driver_taximeter_sessions where id=p_session_id and driver_id=v_uid for update;
  update public.driver_taximeter_sessions set status='finished',ended_at=now(),end_lat=p_lat,end_lng=p_lng,final_amount=v_amount,payment_method=nullif(trim(coalesce(p_payment_method,'')),''),updated_at=now() where id=p_session_id and driver_id=v_uid;
  return jsonb_build_object('ok',true,'session_id',p_session_id,'status','finished','final_amount',v_amount,'distance_m',v_distance,'elapsed_seconds',v_elapsed,'payment_method',nullif(trim(coalesce(p_payment_method,'')),''));
end;
$$;
revoke all on function public.finish_driver_taximeter(uuid,double precision,double precision,text) from public,anon;
grant execute on function public.finish_driver_taximeter(uuid,double precision,double precision,text) to authenticated;

create or replace function public.cancel_driver_taximeter(p_session_id uuid)
returns jsonb language plpgsql security definer set search_path to 'public','pg_temp' as $$
declare v_uid uuid:=auth.uid();
begin
  if v_uid is null then raise exception 'Não autenticado'; end if;
  update public.driver_taximeter_sessions set status='cancelled',ended_at=now(),updated_at=now() where id=p_session_id and driver_id=v_uid and status='running';
  if not found then raise exception 'Taxímetro não está em andamento'; end if;
  return jsonb_build_object('ok',true,'session_id',p_session_id,'status','cancelled');
end;
$$;
revoke all on function public.cancel_driver_taximeter(uuid) from public,anon;
grant execute on function public.cancel_driver_taximeter(uuid) to authenticated;
