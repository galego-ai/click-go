create table if not exists public.driver_taximeter_sessions (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null references public.drivers(id) on delete cascade,
  franchise_id uuid references public.franchises(id) on delete set null,
  city_id uuid references public.cities(id) on delete set null,
  category_id uuid not null references public.ride_categories(id) on delete restrict,
  status text not null default 'running' check (status in ('running','finished','cancelled')),
  base_fare numeric(12,2) not null default 0 check (base_fare >= 0),
  price_per_km numeric(12,4) not null default 0 check (price_per_km >= 0),
  price_per_minute numeric(12,4) not null default 0 check (price_per_minute >= 0),
  minimum_fare numeric(12,2) not null default 0 check (minimum_fare >= 0),
  multiplier numeric(8,3) not null default 1 check (multiplier between 1 and 10),
  started_at timestamptz not null default now(),
  last_tick_at timestamptz not null default now(),
  ended_at timestamptz,
  start_lat double precision check (start_lat is null or start_lat between -90 and 90),
  start_lng double precision check (start_lng is null or start_lng between -180 and 180),
  last_lat double precision check (last_lat is null or last_lat between -90 and 90),
  last_lng double precision check (last_lng is null or last_lng between -180 and 180),
  end_lat double precision check (end_lat is null or end_lat between -90 and 90),
  end_lng double precision check (end_lng is null or end_lng between -180 and 180),
  distance_m numeric(14,2) not null default 0 check (distance_m >= 0),
  elapsed_seconds integer not null default 0 check (elapsed_seconds >= 0),
  current_amount numeric(12,2) not null default 0 check (current_amount >= 0),
  final_amount numeric(12,2),
  payment_method text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists driver_taximeter_one_running_idx on public.driver_taximeter_sessions(driver_id) where status='running';
create index if not exists driver_taximeter_driver_time_idx on public.driver_taximeter_sessions(driver_id,started_at desc);
create index if not exists driver_taximeter_franchise_time_idx on public.driver_taximeter_sessions(franchise_id,started_at desc);

create table if not exists public.driver_taximeter_points (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.driver_taximeter_sessions(id) on delete cascade,
  driver_id uuid not null references public.drivers(id) on delete cascade,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  distance_from_prev_m numeric(12,2),
  accepted boolean not null default true,
  recorded_at timestamptz not null default now()
);
create index if not exists driver_taximeter_points_session_time_idx on public.driver_taximeter_points(session_id,recorded_at);

alter table public.driver_taximeter_sessions enable row level security;
alter table public.driver_taximeter_points enable row level security;
revoke all on public.driver_taximeter_sessions from anon, authenticated;
revoke all on public.driver_taximeter_points from anon, authenticated;
grant select on public.driver_taximeter_sessions to authenticated;
grant select on public.driver_taximeter_points to authenticated;

